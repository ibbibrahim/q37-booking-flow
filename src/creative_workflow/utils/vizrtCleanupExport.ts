import ExcelJS from 'exceljs';
import { format } from 'date-fns';
import type { VizrtCleanupItem } from '../types/creative';

function triggerBlobDownload(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

const fmtDate = (iso: string) => format(new Date(iso), 'yyyy-MM-dd');
const fmtDateTime = (iso: string) => format(new Date(iso), 'yyyy-MM-dd HH:mm');

// Excel list of every image name whose validity has run out — what Graphics deletes from Vizrt.
export async function exportVizrtCleanupList(items: VizrtCleanupItem[]): Promise<void> {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'Q37 Workflow';
  const sheet = workbook.addWorksheet('Vizrt Cleanup', {
    views: [{ state: 'frozen', ySplit: 1 }],
  });

  sheet.columns = [
    { header: 'Image Name', width: 44 },
    { header: 'Request #', width: 12 },
    { header: 'Title', width: 36 },
    { header: 'Type', width: 22 },
    { header: 'Program / Screen', width: 26 },
    { header: 'Air Date', width: 14 },
    { header: 'Validity', width: 14 },
    { header: 'Delete After', width: 14 },
    { header: 'Generated By', width: 22 },
    { header: 'Generated At', width: 20 },
  ];
  sheet.getRow(1).font = { bold: true };

  for (const item of items) {
    sheet.addRow([
      item.imageName,
      item.requestId,
      item.requestTitle,
      item.requestType,
      item.identifier ?? '',
      fmtDate(item.airDate),
      item.validity,
      fmtDate(item.deleteAfter),
      item.generatedBy ?? '',
      fmtDateTime(item.generatedAt),
    ]);
  }

  const buf = await workbook.xlsx.writeBuffer();
  const blob = new Blob([buf], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
  triggerBlobDownload(blob, `Vizrt_Cleanup_${format(new Date(), 'yyyy-MM-dd')}.xlsx`);
}
